 insert into public.reward_catalog(name,kind,visual,price) values('TEST achat','avatar','⭐',20) returning id into c;
 perform public.reward_buy(c);
 if (select balance from public.reward_wallets where user_id=auth.uid())<>before_balance+180 then raise exception 'ÉCHEC : débit';end if;
 blocked:=false;begin perform public.reward_buy(c);exception when others then blocked:=true;end;
 if not blocked then raise exception 'ÉCHEC : achat en double';end if;
 perform public.reward_equip('avatar',c);
 if not exists(select 1 from public.reward_equipment where user_id=auth.uid() and item_id=c) then raise exception 'ÉCHEC : équipement';end if;
 perform public.reward_equip('avatar',null);
 blocked:=false;begin perform public.reward_equip('title',c);exception when others then blocked:=true;end;
 if not blocked then raise exception 'ÉCHEC : mauvais emplacement';end if;
