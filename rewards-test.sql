begin;
select set_config('request.jwt.claim.sub',(select id::text from public.profiles where role='admin' limit 1),true);
set local role authenticated;
do $$
declare m uuid; n uuid; c uuid; b integer; before_balance integer; blocked boolean;
begin
 select coalesce((select balance from public.reward_wallets where user_id=auth.uid()),0) into before_balance;
 insert into public.reward_missions(title,instructions,points,created_by) values('TEST rollback','Critères du test',200,auth.uid()) returning id into m;
 insert into public.reward_missions(title,instructions,points,created_by) values('TEST deuxième','Critères du test',10,auth.uid()) returning id into n;
 perform public.reward_mission_action(m,'reserve');
 blocked:=false;begin perform public.reward_mission_action(n,'reserve');exception when others then blocked:=true;end;
 if not blocked then raise exception 'ÉCHEC : deux réservations actives';end if;
 perform public.reward_mission_action(m,'submit','Travail vérifié pendant le test');
 perform public.reward_mission_action(m,'reject','Correction nécessaire');
 if (select status from public.reward_missions where id=m)<>'open' then raise exception 'ÉCHEC : rejet';end if;
 perform public.reward_mission_action(m,'reserve');
 perform public.reward_mission_action(m,'submit','Correction terminée');
 perform public.reward_mission_action(m,'approve');
