select set_config('request.jwt.claim.sub',(select id::text from public.profiles where role='lecture' limit 1),true);
set local role authenticated;
do $$ declare blocked boolean; c uuid; begin
 if (select count(*) from public.reward_catalog)<15 then raise exception 'ÉCHEC : catalogue invisible';end if;
 if exists(select 1 from public.reward_missions) or exists(select 1 from public.reward_wallets) or exists(select 1 from public.reward_inventory) or exists(select 1 from public.reward_ledger) then raise exception 'ÉCHEC : données admin exposées';end if;
 select id into c from public.reward_catalog limit 1;
 blocked:=false;begin perform public.reward_buy(c);exception when others then blocked:=true;end;
 if not blocked then raise exception 'ÉCHEC : achat employé';end if;
 blocked:=false;begin perform public.reward_equip('avatar',c);exception when others then blocked:=true;end;
 if not blocked then raise exception 'ÉCHEC : équipement employé';end if;
 blocked:=false;begin perform public.reward_mission_action(gen_random_uuid(),'reserve');exception when others then blocked:=true;end;
 if not blocked then raise exception 'ÉCHEC : mission employé';end if;
 blocked:=false;begin insert into public.reward_wallets(user_id,balance) values(auth.uid(),999);exception when others then blocked:=true;end;
 if not blocked then raise exception 'ÉCHEC : écriture directe';end if;
 update public.reward_catalog set price=1;
 if found then raise exception 'ÉCHEC : prix modifiable';end if;
 blocked:=false;
 begin update public.profiles set role='admin' where id=auth.uid();
 exception when insufficient_privilege then blocked:=true;
 when others then if sqlerrm='Only an administrator can change display name, email or role' then blocked:=true;else raise;end if;
 end;
 if not blocked then raise exception 'ÉCHEC : élévation du rôle';end if;
end $$;
