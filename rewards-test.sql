select set_config('request.jwt.claim.sub',(select id::text from public.profiles where role='responsable' limit 1),true);
set local role authenticated;
do $$ declare blocked boolean;begin
 if exists(select 1 from public.reward_missions) then raise exception 'ÉCHEC : missions visibles responsable';end if;
 blocked:=false;begin perform public.reward_mission_action(gen_random_uuid(),'approve');exception when others then blocked:=true;end;
 if not blocked then raise exception 'ÉCHEC : validation responsable';end if;
end $$;
set local role anon;
do $$ declare blocked boolean;begin
 blocked:=false;begin perform * from public.reward_catalog;exception when insufficient_privilege then blocked:=true;end;
 if not blocked then raise exception 'ÉCHEC : catalogue anonyme';end if;
 blocked:=false;begin perform public.reward_buy(gen_random_uuid());exception when insufficient_privilege then blocked:=true;end;
 if not blocked then raise exception 'ÉCHEC : RPC anonyme';end if;
end $$;
